import { randomBytes } from 'node:crypto'
import { PayPalAgentToolkit } from '@paypal/agent-toolkit/openai'
import { config, modes } from '../config.js'
import { isOutage, degrade } from '../fallback.js'

// Only the actions this app needs. Everything else in the toolkit stays disabled.
const ACTIONS = {
  orders: { create: true, get: true, capture: true },
  payments: { createRefund: true, getRefunds: true },
  shipment: { create: true, get: true },
  disputes: { list: true, get: true, create: true },
}

// The toolkit defaults to the LIVE PayPal API unless context.sandbox is true.
const toolkit = new PayPalAgentToolkit({
  clientId: config.paypalClientId || 'mock-client-id',
  clientSecret: config.paypalClientSecret || 'mock-client-secret',
  configuration: { actions: ACTIONS, context: { sandbox: true } },
})

const toolkitTools = new Map(toolkit.getTools().map((t) => [t.function.name, t.function]))

// JSON Schema generated by the toolkit (zod-to-json-schema), reshaped for Claude's input_schema.
export function toolkitSchema(name) {
  const fn = toolkitTools.get(name)
  if (!fn) throw new Error(`PayPal toolkit tool ${name} is not enabled`)
  const { $schema, ...schema } = fn.parameters
  return { description: fn.description.trim(), input_schema: schema }
}

let callCounter = 0

async function liveCall(name, args) {
  callCounter += 1
  const result = await toolkit.handleToolCall({
    id: `call_${callCounter}`,
    type: 'function',
    function: { name, arguments: JSON.stringify(args) },
  })
  const parsed = JSON.parse(result.content)
  if (parsed && parsed.error) {
    const message = typeof parsed.error === 'string' ? parsed.error : parsed.error.message || JSON.stringify(parsed.error)
    throw new Error(`PayPal ${name}: ${message}`)
  }
  return parsed
}

// ---------------- PayPal REST: authorize now, capture each package on delivery ----------------
// The Agent Toolkit creates CAPTURE orders only, so the hold-and-capture flow calls the Orders and
// Payments REST APIs directly. Refunds, tracking and disputes still go through the toolkit.

export const REST_CALLS = new Set(['create_authorize_order', 'authorize_order', 'capture_authorization', 'void_authorization'])
const API_BASE = 'https://api-m.sandbox.paypal.com'
let token = { value: null, expires: 0 }

async function accessToken() {
  if (token.value && Date.now() < token.expires - 60000) return token.value
  const basic = Buffer.from(`${config.paypalClientId}:${config.paypalClientSecret}`).toString('base64')
  const res = await fetch(`${API_BASE}/v1/oauth2/token`, {
    method: 'POST',
    headers: { Authorization: `Basic ${basic}`, 'Content-Type': 'application/x-www-form-urlencoded' },
    body: 'grant_type=client_credentials',
  })
  if (!res.ok) throw new Error(`PayPal oauth: ${res.status} unauthorized`)
  const data = await res.json()
  token = { value: data.access_token, expires: Date.now() + data.expires_in * 1000 }
  return token.value
}

async function rest(method, path, body) {
  const res = await fetch(`${API_BASE}${path}`, {
    method,
    headers: { Authorization: `Bearer ${await accessToken()}`, 'Content-Type': 'application/json', 'PayPal-Request-Id': randomBytes(12).toString('hex') },
    body: body === undefined ? undefined : JSON.stringify(body),
  })
  const text = await res.text()
  const data = text ? JSON.parse(text) : {}
  if (!res.ok) {
    const issue = data.details?.[0]?.issue || data.name || res.status
    throw new Error(`PayPal ${path.split('/').slice(-1)[0]}: ${issue} (${res.status})`)
  }
  return data
}

function orderRequest({ items, shippingCost, returnUrl, cancelUrl }) {
  const subtotal = round2(items.reduce((s, i) => s + i.itemCost * i.quantity, 0))
  const total = round2(subtotal + (shippingCost || 0))
  return {
    intent: 'AUTHORIZE',
    purchase_units: [{
      amount: { ...money(total), breakdown: { item_total: money(subtotal), shipping: money(shippingCost || 0) } },
      items: items.map((i) => ({ name: i.name, description: i.description, quantity: String(i.quantity), unit_amount: money(i.itemCost) })),
    }],
    payment_source: { paypal: { experience_context: { return_url: returnUrl, cancel_url: cancelUrl, user_action: 'CONTINUE', shipping_preference: 'NO_SHIPPING' } } },
  }
}

const restHandlers = {
  create_authorize_order: (args) => rest('POST', '/v2/checkout/orders', orderRequest(args)),
  authorize_order: ({ id }) => rest('POST', `/v2/checkout/orders/${id}/authorize`, {}),
  capture_authorization: ({ authorization_id, amount, final_capture, invoice_id }) =>
    rest('POST', `/v2/payments/authorizations/${authorization_id}/capture`, { amount: money(amount), final_capture, invoice_id }),
  void_authorization: async ({ authorization_id }) => {
    await rest('POST', `/v2/payments/authorizations/${authorization_id}/void`)
    return { id: authorization_id, status: 'VOIDED' }
  },
}

export function authorizationOf(order) {
  return order?.purchase_units?.[0]?.payments?.authorizations?.[0] || null
}

// ---------------- MOCK PayPal (same response shapes as the sandbox) ----------------

const mock = { orders: new Map(), captures: new Map(), refunds: new Map(), trackers: new Map(), disputes: new Map(), authorizations: new Map() }
const ALNUM = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'

function mockId(length = 17) {
  const bytes = randomBytes(length)
  return Array.from(bytes, (b) => ALNUM[b % ALNUM.length]).join('')
}

const money = (value) => ({ currency_code: 'USD', value: Number(value).toFixed(2) })
const round2 = (n) => Math.round(n * 100) / 100

function refundedTotal(captureId) {
  return round2([...mock.refunds.values()].filter((r) => r.capture_id === captureId).reduce((s, r) => s + Number(r.amount.value), 0))
}

const mockHandlers = {
  create_order(args) {
    const subtotal = args.items.reduce((s, i) => s + i.itemCost * i.quantity, 0)
    const total = round2(subtotal + (args.shippingCost || 0) - (args.discount || 0))
    const id = mockId()
    const order = {
      id,
      intent: 'CAPTURE',
      status: 'PAYER_ACTION_REQUIRED',
      create_time: new Date().toISOString(),
      purchase_units: [{
        amount: { ...money(total), breakdown: { item_total: money(subtotal), shipping: money(args.shippingCost || 0) } },
        items: args.items.map((i) => ({ name: i.name, quantity: String(i.quantity), unit_amount: money(i.itemCost) })),
      }],
      links: [
        { rel: 'self', href: `mock://v2/checkout/orders/${id}`, method: 'GET' },
        { rel: 'payer-action', href: `${config.publicUrl}/mock-paypal/checkout?token=${id}`, method: 'GET' },
      ],
      _returnUrl: args.returnUrl,
      _cancelUrl: args.cancelUrl,
    }
    mock.orders.set(id, order)
    return publicOrder(order)
  },
  get_order({ id }) {
    const order = mock.orders.get(id)
    if (!order) throw new Error(`PayPal get_order: RESOURCE_NOT_FOUND ${id}`)
    return publicOrder(order)
  },
  pay_order({ id }) {
    const order = mock.orders.get(id)
    if (!order) throw new Error(`PayPal pay_order: RESOURCE_NOT_FOUND ${id}`)
    if (order.status !== 'APPROVED') throw new Error('PayPal pay_order: ORDER_NOT_APPROVED')
    const capture = {
      id: mockId(),
      status: 'COMPLETED',
      amount: { ...order.purchase_units[0].amount },
      create_time: new Date().toISOString(),
    }
    delete capture.amount.breakdown
    mock.captures.set(capture.id, { ...capture, order_id: id })
    order.status = 'COMPLETED'
    order.purchase_units[0].payments = { captures: [capture] }
    return { status: 'success', response: publicOrder(order) }
  },
  create_authorize_order(args) {
    const order = mockHandlers.create_order({ ...args, items: args.items })
    mock.orders.get(order.id).intent = 'AUTHORIZE'
    return publicOrder(mock.orders.get(order.id))
  },
  authorize_order({ id }) {
    const order = mock.orders.get(id)
    if (!order) throw new Error(`PayPal authorize: RESOURCE_NOT_FOUND ${id}`)
    if (order.status !== 'APPROVED') throw new Error('PayPal authorize: ORDER_NOT_APPROVED')
    const authorization = { id: mockId(), status: 'CREATED', amount: money(order.purchase_units[0].amount.value), captured: 0 }
    mock.authorizations.set(authorization.id, authorization)
    order.status = 'COMPLETED'
    order.purchase_units[0].payments = { authorizations: [{ id: authorization.id, status: 'CREATED', amount: authorization.amount }] }
    return publicOrder(order)
  },
  capture_authorization({ authorization_id, amount, final_capture }) {
    const auth = mock.authorizations.get(authorization_id)
    if (!auth) throw new Error(`PayPal capture: RESOURCE_NOT_FOUND ${authorization_id}`)
    if (['VOIDED', 'CAPTURED'].includes(auth.status)) throw new Error('PayPal capture: AUTHORIZATION_ALREADY_COMPLETED')
    if (round2(auth.captured + Number(amount)) > Number(auth.amount.value) + 0.001) throw new Error('PayPal capture: MAX_CAPTURE_AMOUNT_EXCEEDED')
    const capture = { id: mockId(), status: 'COMPLETED', amount: money(amount), final_capture: !!final_capture, create_time: new Date().toISOString() }
    mock.captures.set(capture.id, { ...capture, authorization_id })
    auth.captured = round2(auth.captured + Number(amount))
    auth.status = final_capture ? 'CAPTURED' : 'PARTIALLY_CAPTURED'
    return capture
  },
  void_authorization({ authorization_id }) {
    const auth = mock.authorizations.get(authorization_id)
    if (!auth) throw new Error(`PayPal void: RESOURCE_NOT_FOUND ${authorization_id}`)
    if (['VOIDED', 'CAPTURED'].includes(auth.status)) throw new Error('PayPal void: AUTHORIZATION_ALREADY_COMPLETED')
    auth.status = 'VOIDED'
    return { id: authorization_id, status: 'VOIDED' }
  },
  create_refund({ capture_id, amount, note_to_payer }) {
    const capture = mock.captures.get(capture_id)
    if (!capture) throw new Error(`PayPal create_refund: capture ${capture_id} not found`)
    const remaining = round2(Number(capture.amount.value) - refundedTotal(capture_id))
    const value = amount ? Number(amount.value) : remaining
    if (!(value > 0) || value > remaining) throw new Error('PayPal create_refund: REFUND_AMOUNT_EXCEEDED')
    const refund = { id: mockId(), status: 'COMPLETED', amount: money(value), capture_id, note_to_payer: note_to_payer || null, create_time: new Date().toISOString() }
    mock.refunds.set(refund.id, refund)
    capture.status = refundedTotal(capture_id) >= Number(capture.amount.value) ? 'REFUNDED' : 'PARTIALLY_REFUNDED'
    return refund
  },
  get_refund({ refund_id }) {
    const refund = mock.refunds.get(refund_id)
    if (!refund) throw new Error(`PayPal get_refund: RESOURCE_NOT_FOUND ${refund_id}`)
    return refund
  },
  create_shipment_tracking({ transaction_id, tracking_number, status = 'SHIPPED', carrier = 'OTHER' }) {
    const tracker = { transaction_id, tracking_number, status, carrier, last_updated_time: new Date().toISOString() }
    mock.trackers.set(transaction_id, [...(mock.trackers.get(transaction_id) || []), tracker])
    return { tracker_identifiers: [{ transaction_id, tracking_number }], errors: [] }
  },
  get_shipment_tracking({ order_id, transaction_id }) {
    let txn = transaction_id
    if (!txn && order_id) txn = mock.orders.get(order_id)?.purchase_units[0].payments?.captures?.[0]?.id
    if (!txn) throw new Error('Either transaction_id or order_id must be provided.')
    return { trackers: mock.trackers.get(txn) || [] }
  },
  list_disputes({ disputed_transaction_id } = {}) {
    const items = [...mock.disputes.values()].filter((d) => !disputed_transaction_id || d.disputed_transactions[0].seller_transaction_id === disputed_transaction_id)
    return { items: items.map(({ messages, ...summary }) => summary) }
  },
  get_dispute({ dispute_id }) {
    const dispute = mock.disputes.get(dispute_id)
    if (!dispute) throw new Error(`PayPal get_dispute: RESOURCE_NOT_FOUND ${dispute_id}`)
    return dispute
  },
  accept_dispute_claim({ dispute_id, note }) {
    const dispute = mock.disputes.get(dispute_id)
    if (!dispute) throw new Error(`PayPal accept_dispute_claim: RESOURCE_NOT_FOUND ${dispute_id}`)
    if (dispute.status === 'RESOLVED') throw new Error('PayPal accept_dispute_claim: DISPUTE_ALREADY_RESOLVED')
    const captureId = dispute.disputed_transactions[0].seller_transaction_id
    const refund = mockHandlers.create_refund({ capture_id: captureId, amount: dispute.dispute_amount })
    dispute.status = 'RESOLVED'
    dispute.dispute_outcome = { outcome_code: 'RESOLVED_BUYER_FAVOUR', amount_refunded: refund.amount }
    dispute.messages.push({ posted_by: 'SELLER', content: note, time_posted: new Date().toISOString() })
    dispute.update_time = new Date().toISOString()
    return { links: [{ rel: 'self', href: `mock://v1/customer/disputes/${dispute_id}` }] }
  },
}

function publicOrder(order) {
  const { _returnUrl, _cancelUrl, ...rest } = order
  return JSON.parse(JSON.stringify(rest))
}

// Mock-only helpers that stand in for the buyer using PayPal's own UI.
export const mockPaypal = {
  approve(orderId) {
    const order = mock.orders.get(orderId)
    if (!order) return null
    if (order.status === 'PAYER_ACTION_REQUIRED') order.status = 'APPROVED'
    return { returnUrl: order._returnUrl, cancelUrl: order._cancelUrl, order: publicOrder(order) }
  },
  peek(orderId) {
    const order = mock.orders.get(orderId)
    return order ? { ...publicOrder(order), returnUrl: order._returnUrl, cancelUrl: order._cancelUrl } : null
  },
  openDispute({ captureId, amount, reason, message }) {
    const id = `PP-D-${mockId(8)}`
    const now = new Date().toISOString()
    const dispute = {
      dispute_id: id,
      create_time: now,
      update_time: now,
      reason,
      status: 'OPEN',
      dispute_state: 'REQUIRED_ACTION',
      dispute_amount: money(amount),
      disputed_transactions: [{ seller_transaction_id: captureId }],
      messages: [{ posted_by: 'BUYER', content: message, time_posted: now }],
    }
    mock.disputes.set(id, dispute)
    return dispute
  },
}

export async function callPaypal(name, args) {
  if (modes.paypal === 'mock') {
    const handler = mockHandlers[name]
    if (!handler) throw new Error(`Mock PayPal has no handler for ${name}`)
    return JSON.parse(JSON.stringify(handler(args)))
  }
  try {
    return REST_CALLS.has(name) ? await restHandlers[name](args) : await liveCall(name, args)
  } catch (err) {
    if (!isOutage(err)) throw err
    // Only switch for good when the credentials stop working. Network blips and 5xx stay live,
    // because orders already created in the sandbox cannot be finished on the stand-in.
    if (!/invalid_client|Client Authentication failed|\b401\b|unauthori[sz]ed/i.test(String(err.message))) {
      throw new Error('PayPal sandbox did not answer. Please try again in a moment.')
    }
    degrade('paypal', err)
    if (name === 'create_order' || name === 'create_authorize_order') return callPaypal(name, args)
    throw new Error('PayPal sandbox is unavailable right now. New orders use the built-in demo checkout.')
  }
}

